CREATE TABLE inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE,
    product_type VARCHAR(32) NOT NULL,
    quantity_on_hand BIGINT NOT NULL DEFAULT 0,
    quantity_reserved BIGINT NOT NULL DEFAULT 0,
    low_stock_threshold BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_product_id_positive CHECK (product_id > 0),
    CONSTRAINT ck_inventory_product_type CHECK (product_type IN ('SINGLE_UNIT', 'MULTI_UNIT')),
    CONSTRAINT ck_inventory_quantity_on_hand_nonnegative CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_inventory_quantity_reserved_nonnegative CHECK (quantity_reserved >= 0),
    CONSTRAINT ck_inventory_reserved_within_stock CHECK (quantity_reserved <= quantity_on_hand),
    CONSTRAINT ck_inventory_low_stock_threshold_nonnegative CHECK (low_stock_threshold >= 0),
    CONSTRAINT ck_inventory_single_unit_quantity CHECK (
        product_type <> 'SINGLE_UNIT' OR quantity_on_hand <= 1
    )
);

CREATE TABLE inventory_reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    expired_at TIMESTAMPTZ,
    CONSTRAINT ck_inventory_reservation_order_id_positive CHECK (order_id > 0),
    CONSTRAINT ck_inventory_reservation_status CHECK (
        status IN ('ACTIVE', 'CONFIRMED', 'RELEASED', 'EXPIRED')
    ),
    CONSTRAINT ck_inventory_reservation_expiration CHECK (expires_at > created_at),
    CONSTRAINT ck_inventory_reservation_terminal_timestamp CHECK (
        (status = 'ACTIVE' AND confirmed_at IS NULL AND released_at IS NULL AND expired_at IS NULL)
        OR (status = 'CONFIRMED' AND confirmed_at IS NOT NULL AND released_at IS NULL AND expired_at IS NULL)
        OR (status = 'RELEASED' AND confirmed_at IS NULL AND released_at IS NOT NULL AND expired_at IS NULL)
        OR (status = 'EXPIRED' AND confirmed_at IS NULL AND released_at IS NULL AND expired_at IS NOT NULL)
    )
);

CREATE TABLE inventory_reservation_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    CONSTRAINT fk_inventory_reservation_item_reservation
        FOREIGN KEY (reservation_id) REFERENCES inventory_reservation (id),
    CONSTRAINT fk_inventory_reservation_item_inventory
        FOREIGN KEY (product_id) REFERENCES inventory (product_id),
    CONSTRAINT uq_inventory_reservation_item_product UNIQUE (reservation_id, product_id),
    CONSTRAINT ck_inventory_reservation_item_quantity_positive CHECK (quantity > 0)
);

CREATE TABLE inventory_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    movement_type VARCHAR(32) NOT NULL,
    quantity_delta BIGINT NOT NULL,
    reason VARCHAR(500) NOT NULL,
    order_id BIGINT,
    reservation_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_inventory_movement_inventory
        FOREIGN KEY (product_id) REFERENCES inventory (product_id),
    CONSTRAINT fk_inventory_movement_reservation
        FOREIGN KEY (reservation_id) REFERENCES inventory_reservation (id),
    CONSTRAINT ck_inventory_movement_type CHECK (
        movement_type IN ('ENTRY', 'MANUAL_EXIT', 'ADJUSTMENT', 'RESERVATION_CONFIRMATION')
    ),
    CONSTRAINT ck_inventory_movement_delta_nonzero CHECK (quantity_delta <> 0),
    CONSTRAINT ck_inventory_movement_direction CHECK (
        (movement_type = 'ENTRY' AND quantity_delta > 0)
        OR (movement_type IN ('MANUAL_EXIT', 'RESERVATION_CONFIRMATION') AND quantity_delta < 0)
        OR movement_type = 'ADJUSTMENT'
    ),
    CONSTRAINT ck_inventory_movement_reason_nonempty CHECK (BTRIM(reason) <> '')
);

CREATE INDEX ix_inventory_product_type ON inventory (product_type);
CREATE INDEX ix_inventory_low_stock ON inventory (quantity_on_hand, low_stock_threshold);
CREATE INDEX ix_inventory_reservation_active_expiration
    ON inventory_reservation (expires_at)
    WHERE status = 'ACTIVE';
CREATE INDEX ix_inventory_reservation_item_product
    ON inventory_reservation_item (product_id);
CREATE INDEX ix_inventory_movement_product_created
    ON inventory_movement (product_id, created_at DESC, id DESC);
CREATE INDEX ix_inventory_movement_created
    ON inventory_movement (created_at DESC, id DESC);
